import { describe, expect, test } from 'vitest';
import {
  documentSkipReason,
  isEnvFile,
  MENTOR_LIMITS,
  pickReady,
  retryDelay,
} from '../../src/core/scheduler';

const now = 10 * 3_600_000;
const limits = { ...MENTOR_LIMITS, perTrigger: 2, perHour: 3, perDay: 5, cooldownMs: 60_000 };

describe('pickReady', () => {
  test('ошибки в функции и cooldown откладывают разбор', () => {
    const result = pickReady(
      [
        { key: 'typing', hasErrors: true },
        { key: 'fresh', hasErrors: false, reviewedAt: now - 10_000 },
        { key: 'old', hasErrors: false, reviewedAt: now - 120_000 },
      ],
      [],
      now,
      limits,
    );
    expect(result).toEqual({
      ready: ['old'],
      skipped: [
        { key: 'typing', reason: 'errors' },
        { key: 'fresh', reason: 'cooldown' },
      ],
    });
  });

  const many = ['a', 'b', 'c'].map((key) => ({ key, hasErrors: false }));

  test('за один триггер — не больше perTrigger', () => {
    expect(pickReady(many, [], now, limits).ready).toEqual(['a', 'b']);
  });

  test('лимит в час: считаются запросы за последний час', () => {
    const sent = [now - 3_700_000, now - 1_000, now - 2_000];
    expect(pickReady(many, sent, now, limits).ready).toEqual(['a']);
  });

  test('лимит в сутки', () => {
    const sent = [1, 2, 3, 4].map((h) => now - h * 3_600_000 - 1);
    const result = pickReady(many, [...sent, now - 1], now, limits);
    expect(result.ready).toEqual([]);
    expect(result.skipped.map((s) => s.reason)).toEqual(['limit', 'limit', 'limit']);
  });
});

test('retryDelay: 1, 2, 4… минуты, потолок 15', () => {
  expect([1, 2, 3, 5, 10].map(retryDelay)).toEqual([60_000, 120_000, 240_000, 900_000, 900_000]);
});

describe('documentSkipReason', () => {
  const ok = { path: '/home/me/study/cart.js', languageId: 'javascript', lineCount: 40, head: [] };

  test('обычный учебный файл автопилот смотрит', () => {
    expect(documentSkipReason(ok)).toBeUndefined();
    expect(documentSkipReason({ ...ok, path: 'C:\\study\\main.py', languageId: 'python' })).toBe(
      undefined,
    );
  });

  test('не смотрит .env, чужие языки, сборку, зависимости, большие и минифицированные файлы', () => {
    const reasons = [
      { path: '/p/.env.local' },
      { languageId: 'markdown' },
      { path: '/p/node_modules/lib/index.js' },
      { path: 'C:\\p\\dist\\extension.js' },
      { path: '/p/vendor.min.js' },
      { lineCount: 5000 },
      { head: ['var a=' + 'x'.repeat(600)] },
      { head: ['// Code generated by protoc. DO NOT EDIT.'] },
    ].map((over) => documentSkipReason({ ...ok, ...over }));
    expect(reasons.every(Boolean)).toBe(true);
  });

  test('isEnvFile', () => {
    expect(isEnvFile('/p/.env')).toBe(true);
    expect(isEnvFile('C:\\p\\.ENV.production')).toBe(true);
    expect(isEnvFile('/p/env.js')).toBe(false);
  });
});
